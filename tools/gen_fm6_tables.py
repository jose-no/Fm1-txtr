def arr(name, ctype, vals, per=10):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    L = ["/* Generated by tools/gen_fm6_tables.py: msfa's start-up tables for fm6_core.c at 44.1 kHz. Do not edit. */",
         "#ifndef FM6_TABLES_H", "#define FM6_TABLES_H", "#include <stdint.h>",
         f"#define FM6_LFO_UNIT {int(CTL * 25190424 / FS + 0.5)}",
         f"#define FM6_PENV_UNIT {int(CTL * (1 << 24) / (21.3 * FS) + 0.5)}",
         f"#define FM6_FREQ_R {int(round(2 ** 40 / FS))}u",
         f"#define FM6_AMS_C0 {int(round(12.2 * math.log2(math.e) * 2 ** 24))}",
         f"#define FM6_AMS_K {int(round(0.07 / 262144 * math.log2(math.e) * 2 ** 24 * 1024))}"]
    L += arr("SINE", "int16_t", [int(round(32767 * math.sin(2 * math.pi * i / 1024))) for i in range(1025)], 16)
    L += arr("FM6_EXP2", "uint32_t", [int(round((1 << 30) * (2 ** (i / 1024) - 1))) for i in range(1025)], 8)
    lforatio = int(4437500000.0 * CTL / FS)
    L += arr("FM6_LFO_DELTA", "uint32_t", [int(s * lforatio) for s in LFO_SOURCE], 8)
    base, step = 50857777, (1 << 24) // 12
    L += arr("FM6_DETUNE", "uint16_t",
             [int(round(0.0209 * math.exp(-0.396 * ((base + step * mn) / (1 << 24))) / 7 * (base + step * mn)))
              for mn in range(128)], 16)
    L += arr("FM6_FINE", "int32_t", [int(math.floor(24204406.323123 * math.log(1 + 0.01 * f) + 0.5)) for f in range(100)])
    L += ["#endif", ""]
    with open(os.path.join(root, "third_party", "fm6", "fm6_tables.h"), "w") as f:
        f.write("\n".join(L))
    print("third_party/fm6/fm6_tables.h")


if __name__ == "__main__":
    main()
