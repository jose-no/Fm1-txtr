"""Generate the parameter tables from params/params.py.

    python3 tools/gen_params.py

Writes core/gen/tx_params.h, core/gen/tx_params.c and web/gen/params.js.
"""
import json
import math
import os
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'params'))
import params as defs  # noqa: E402

RAW_STEPS = 1000            # continuous parameters are stored 0..1000
PAGES = ['SEQ', 'NOTES', 'SOUND', 'GRAIN', 'SPACE', 'MOD']


def cname(pid):
    return 'TXP_' + pid.upper()


def raw_range(c):
    if c.kind in ('lin', 'exp'):
        return 0, RAW_STEPS
    if c.kind == 'int':
        return c.lo, c.hi
    return 0, len(c.labels) - 1


def main():
    ps = defs.PARAMS
    ids = [p['id'] for p in ps]
    assert len(set(ids)) == len(ids), 'duplicate parameter id'

    # stable ids for saved patches: a hash of the id string
    uids = {}
    for p in ps:
        u = zlib.crc32(p['id'].encode()) & 0xFFFF
        if u in uids.values():
            sys.exit(f'uid collision for {p["id"]}: rename it')
        uids[p['id']] = u

    # mod targets: index 0 is "None"
    targets = [i for i, p in enumerate(ps) if p['mod']]
    page_abbr = {'SEQ': 'SEQ', 'NOTES': 'NOT', 'SOUND': 'SND', 'GRAIN': 'GRN', 'SPACE': 'SPC', 'MOD': 'MOD'}
    target_labels = ['None'] + [f'{page_abbr[ps[i]["page"]]} {ps[i]["name"]}' for i in targets]
    target_index = {ps[i]['id']: n + 1 for n, i in enumerate(targets)}

    subs = []                       # (page, sub) in order of appearance
    for p in ps:
        if (p['page'], p['sub']) not in subs:
            subs.append((p['page'], p['sub']))
    for pg, _ in subs:
        assert pg in PAGES, pg

    rows = []
    for i, p in enumerate(ps):
        c = p['curve']
        if c.kind == 'enum' and c.labels == ['@targets']:
            labels, values = target_labels, None
        elif c.kind == 'enum':
            labels, values = c.labels, c.values
        else:
            labels, values = None, None
        if c.kind == 'enum':
            rmin, rmax = 0, len(labels) - 1
        else:
            rmin, rmax = raw_range(c)
        d = p['default']
        if c.kind == 'lin':
            rdef = round((d - c.lo) / (c.hi - c.lo) * RAW_STEPS)
        elif c.kind == 'exp':
            rdef = round(math.log(d / c.lo) / math.log(c.hi / c.lo) * RAW_STEPS)
        elif c.kind == 'int':
            rdef = int(d)
        elif labels is target_labels:
            rdef = 0 if d == '@none' else target_index[d]
        elif isinstance(d, (int, float)) and values is not None:
            # a free value on a free-then-sync table: the nearest free entry
            rdef = min((i for i, v in enumerate(values) if v > 0), key=lambda i: abs(math.log(values[i] / d)))
        else:
            rdef = labels.index(d)
        assert rmin <= rdef <= rmax, (p['id'], rdef)
        rows.append(dict(
            id=p['id'], uid=uids[p['id']], name=p['name'], page=p['page'], sub=p['sub'],
            subIndex=subs.index((p['page'], p['sub'])), knob=p['knob'], op=p['op'] or 0,
            curve=c.kind, lo=getattr(c, 'lo', 0), hi=getattr(c, 'hi', 0), unit=c.unit,
            rmin=rmin, rmax=rmax, rdef=rdef, labels=labels, values=values,
            mod=p['mod'], morph=p['morph']))

    gen_c(rows, subs, targets, target_labels)
    gen_js(rows, subs, targets, target_labels)
    print(f'{len(rows)} parameters, {len(subs)} sub-pages, {len(targets)} mod targets')


def cfloat(v):
    s = repr(float(v))
    return s + 'f' if ('.' in s or 'e' in s) else s + '.0f'


def cstr(s):
    return json.dumps(s)


def gen_c(rows, subs, targets, target_labels):
    out = os.path.join(ROOT, 'core', 'gen')
    os.makedirs(out, exist_ok=True)
    n = len(rows)
    h = ['/* Generated by tools/gen_params.py from params/params.py. Do not edit. */',
         '#ifndef TX_PARAMS_H', '#define TX_PARAMS_H', '', '#include <stdint.h>', '',
         f'#define TX_NPARAMS {n}', f'#define TX_NSUBS {len(subs)}', f'#define TX_NPAGES {len(PAGES)}',
         f'#define TX_NMODT {len(target_labels)}   /* mod targets, index 0 = none */',
         f'#define TX_RAW_STEPS {RAW_STEPS}', '',
         'enum {']
    for r in rows:
        h.append(f'    {cname(r["id"])},')
    h += ['};', '',
          'enum { TXC_LIN, TXC_EXP, TXC_INT, TXC_ENUM };',
          'enum { TXF_MOD = 1, TXF_MORPH = 2 };', '',
          'typedef struct {',
          '    uint16_t uid;          /* stable id for saved patches */',
          '    uint8_t curve, flags;',
          '    int16_t rmin, rmax, rdef;',
          '    float lo, hi;          /* TXC_LIN / TXC_EXP: the real range */',
          '    const float *values;   /* TXC_ENUM with numbers, else 0 */',
          '    uint8_t nlabels, sub, knob, op;',
          '} tx_pdef;', '',
          '#ifdef __cplusplus', 'extern "C" {', '#endif',
          'extern const tx_pdef tx_pdefs[TX_NPARAMS];',
          'extern const char *const tx_pnames[TX_NPARAMS];',
          'extern const char *const *const tx_plabels[TX_NPARAMS];   /* TXC_ENUM labels, else 0 */',
          'extern const uint16_t tx_modt[TX_NMODT];                   /* mod target -> parameter (0xFFFF = none) */',
          'extern const char *const tx_pages[TX_NPAGES];',
          'extern const char *const tx_subs[TX_NSUBS];',
          'extern const uint8_t tx_sub_page[TX_NSUBS];',
          '#ifdef __cplusplus', '}', '#endif', '',
          '#endif', '']
    with open(os.path.join(out, 'tx_params.h'), 'w') as f:
        f.write('\n'.join(h))

    c = ['/* Generated by tools/gen_params.py from params/params.py. Do not edit. */',
         '#include "tx_params.h"', '']
    for r in rows:
        if r['values'] is not None:
            c.append(f'static const float v_{r["id"]}[] = {{{", ".join(cfloat(v) for v in r["values"])}}};')
        if r['labels'] is not None and r['labels'] is not target_labels:
            c.append(f'static const char *const l_{r["id"]}[] = {{{", ".join(cstr(x) for x in r["labels"])}}};')
    c.append('static const char *const l_targets[] = {' + ', '.join(cstr(x) for x in target_labels) + '};')
    c += ['', 'const tx_pdef tx_pdefs[TX_NPARAMS] = {']
    curves = {'lin': 'TXC_LIN', 'exp': 'TXC_EXP', 'int': 'TXC_INT', 'enum': 'TXC_ENUM'}
    for r in rows:
        flags = ' | '.join(x for x, on in (('TXF_MOD', r['mod']), ('TXF_MORPH', r['morph'])) if on) or '0'
        vals = f'v_{r["id"]}' if r['values'] is not None else '0'
        nl = len(r['labels']) if r['labels'] else 0
        c.append(f'    {{0x{r["uid"]:04X}, {curves[r["curve"]]}, {flags}, {r["rmin"]}, {r["rmax"]}, {r["rdef"]}, '
                 f'{cfloat(r["lo"])}, {cfloat(r["hi"])}, {vals}, {nl}, {r["subIndex"]}, {r["knob"]}, {r["op"]}}},'
                 f'   /* {r["id"]} */')
    c += ['};', '', 'const char *const tx_pnames[TX_NPARAMS] = {']
    c += [f'    {cstr(r["name"])},' for r in rows]
    c += ['};', '', 'const char *const *const tx_plabels[TX_NPARAMS] = {']
    for r in rows:
        if r['labels'] is target_labels:
            c.append('    l_targets,')
        elif r['labels'] is not None:
            c.append(f'    l_{r["id"]},')
        else:
            c.append('    0,')
    c += ['};', '', 'const uint16_t tx_modt[TX_NMODT] = {0xFFFF, ' + ', '.join(cname(rows[i]['id']) for i in targets) + '};',
          '', 'const char *const tx_pages[TX_NPAGES] = {' + ', '.join(cstr(p) for p in PAGES) + '};',
          'const char *const tx_subs[TX_NSUBS] = {' + ', '.join(cstr(s) for _, s in subs) + '};',
          'const uint8_t tx_sub_page[TX_NSUBS] = {' + ', '.join(str(PAGES.index(p)) for p, _ in subs) + '};', '']
    with open(os.path.join(out, 'tx_params.c'), 'w') as f:
        f.write('\n'.join(c))


def gen_js(rows, subs, targets, target_labels):
    out = os.path.join(ROOT, 'web', 'gen')
    os.makedirs(out, exist_ok=True)
    js_rows = []
    for r in rows:
        x = {k: r[k] for k in ('id', 'uid', 'name', 'page', 'sub', 'knob', 'op', 'curve', 'lo', 'hi', 'unit',
                               'rmin', 'rmax', 'rdef', 'mod', 'morph')}
        if r['labels'] is target_labels:
            x['labels'] = '@targets'
        elif r['labels'] is not None:
            x['labels'] = r['labels']
        if r['values'] is not None:
            x['values'] = r['values']
        js_rows.append(x)
    data = {'rawSteps': RAW_STEPS, 'pages': PAGES, 'subs': [{'page': p, 'name': s} for p, s in subs],
            'targets': [-1] + targets, 'targetLabels': target_labels, 'params': js_rows}
    with open(os.path.join(out, 'params.js'), 'w') as f:
        f.write('// Generated by tools/gen_params.py from params/params.py. Do not edit.\n')
        f.write('export const TX = ' + json.dumps(data, separators=(',', ':')) + ';\n')


if __name__ == '__main__':
    main()
